"""Build web-ready, watermarked copies of the photography portfolio.

Originals live in .photos/originals/ (git-ignored, never published).
Outputs:
  photography/img/full/<name>.jpg   long edge 2400px, watermarked
  photography/img/thumb/<name>.jpg  long edge 900px, watermarked
  photography/photos.js             manifest (file names + sizes only)
  assets/me.jpg                     portrait for the landing page

Only the watermarked web copies are committed; originals stay local.

Usage: python tools/build_photos.py
"""

import json
import os
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".photos" / "originals"
OUT = ROOT / "photography" / "img"
MANIFEST = ROOT / "photography" / "photos.js"
PORTRAIT_SRC = ROOT / ".photos" / "Me.jpg"
PORTRAIT_OUT = ROOT / "assets" / "me.jpg"

WATERMARK = "\u00a9 Stanford White IV"
FONT_CANDIDATES = [
    "C:/Windows/Fonts/segoeuisl.ttf",
    "C:/Windows/Fonts/segoeui.ttf",
    "/System/Library/Fonts/Helvetica.ttc",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
]
SIZES = {"full": 2400, "thumb": 900}
QUALITY = {"full": 84, "thumb": 80}

# Optional per-photo captions / ordering. Photos not listed here are appended
# in file-name order. Set "featured": True to show a photo on the landing page.
CAPTIONS_FILE = ROOT / "tools" / "photo_captions.json"


def load_font(size):
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size)


def watermark(im):
    """Draw the copyright centered along the bottom edge."""
    w, h = im.size
    size = max(14, round(max(w, h) * 0.016))
    font = load_font(size)
    layer = Image.new("RGBA", im.size, (0, 0, 0, 0))
    draw = ImageDraw.Draw(layer)
    left, top, right, bottom = draw.textbbox((0, 0), WATERMARK, font=font)
    tw, th = right - left, bottom - top
    x = (w - tw) // 2 - left
    y = h - th - round(size * 1.1) - top
    shadow = max(1, size // 18)
    draw.text((x + shadow, y + shadow), WATERMARK, font=font, fill=(0, 0, 0, 90))
    draw.text((x, y), WATERMARK, font=font, fill=(255, 255, 255, 170))
    return Image.alpha_composite(im.convert("RGBA"), layer).convert("RGB")


def resized(im, long_edge):
    im = im.copy()
    im.thumbnail((long_edge, long_edge), Image.LANCZOS)
    return im


def main():
    captions = {}
    if CAPTIONS_FILE.exists():
        captions = json.loads(CAPTIONS_FILE.read_text(encoding="utf-8"))

    files = sorted(p for p in SRC.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png"})
    order = {name: i for i, name in enumerate(captions)}
    files.sort(key=lambda p: (order.get(p.stem, len(order)), p.name))

    for kind in SIZES:
        (OUT / kind).mkdir(parents=True, exist_ok=True)

    manifest = []
    for path in files:
        im = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
        name = path.stem.lstrip("_").lower() + ".jpg"
        for kind, edge in SIZES.items():
            out = watermark(resized(im, edge))
            # Saved without EXIF so camera/GPS metadata is not published.
            out.save(OUT / kind / name, "JPEG", quality=QUALITY[kind], optimize=True, progressive=True)
        full_w, full_h = resized(im, SIZES["full"]).size
        meta = captions.get(path.stem, {})
        manifest.append({
            "file": name,
            "w": full_w,
            "h": full_h,
            "caption": meta.get("caption", ""),
            "featured": bool(meta.get("featured", False)),
        })
        print(f"{path.name} -> {name} ({full_w}x{full_h})")

    MANIFEST.write_text(
        "// Generated by tools/build_photos.py. Edit tools/photo_captions.json instead.\n"
        "window.PHOTOS = " + json.dumps(manifest, indent=1) + ";\n",
        encoding="utf-8",
    )

    if PORTRAIT_SRC.exists():
        PORTRAIT_OUT.parent.mkdir(exist_ok=True)
        me = resized(ImageOps.exif_transpose(Image.open(PORTRAIT_SRC)).convert("RGB"), 1000)
        me.save(PORTRAIT_OUT, "JPEG", quality=84, optimize=True, progressive=True)
        print(f"portrait -> {PORTRAIT_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
